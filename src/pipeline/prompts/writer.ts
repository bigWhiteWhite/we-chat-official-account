export function buildCreatePrompt(
  outline: string,
  tags: TagSpec[],
  seriesSection?: string,
): { system: string; prompt: string } {
  const tagLines = formatTagLines(tags);
  const tagSection = tagLines ? `内容标签（说明即创作要求，逐条遵守）：\n${tagLines}\n` : "";
  const series = seriesSection ? `${seriesSection}\n\n` : "";
  return { system: CREATE_SYSTEM_PROMPT, prompt: `${series}${tagSection}大纲/素材：\n${outline}` };
}

/** 修订剧本的 system/prompt：携带大纲、当前剧本与用户意见，要求输出完整新剧本。 */
export function buildRevisePrompt(
  outline: string,
  script: ComicScript,
  message: string,
  seriesSection?: string,
): { system: string; prompt: string } {
  const series = seriesSection ? `${seriesSection}\n\n` : "";
  return {
    system: REVISE_SYSTEM_PROMPT,
    prompt: `${series}大纲/素材：\n${outline}\n\n当前剧本：\n${JSON.stringify(script)}\n\n用户修改意见：\n${message}`,
  };
}
